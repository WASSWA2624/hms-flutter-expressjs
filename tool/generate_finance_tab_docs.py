def parse_source_columns() -> dict[tuple[str, str], list[str]]:
    if not SOURCE.exists():
        raise FileNotFoundError(f"Source specification not found: {SOURCE}")

    columns: dict[tuple[str, str], list[str]] = {}
    current_module: str | None = None
    bullet = re.compile(r"^- \*\*(.+?)\*\* — (.+)$")

    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if line.startswith("### 10.2 "):
            current_module = "billing"
            continue
        if line.startswith("### 10.3 "):
            current_module = "accounts"
            continue
        if line.startswith("### 10.4 "):
            current_module = "claims"
            continue
        if line.startswith("## 11."):
            current_module = None
            continue
        if current_module is None:
            continue

        match = bullet.match(line)
        if not match:
            continue
        raw_label, raw_columns = match.groups()
        labels = (
            JOURNAL_TABS
            if current_module == "accounts"
            and raw_label.startswith("All Journal Entries, General Journal,")
            else [raw_label]
        )
        parsed = [item.strip() for item in raw_columns.split(",") if item.strip()]
        for label in labels:
            columns[(current_module, label)] = parsed
    return columns


def parse_source_tabs() -> dict[str, list[str]]:
    """Read permanent leaf tabs from the three Section 9 menu trees."""

    lines = SOURCE.read_text(encoding="utf-8").splitlines()
    heading_to_module = {
        "### 9.2 Billing": "billing",
        "### 9.3 Accounts & Finance": "accounts",
        "### 9.4 Insurance & Claims": "claims",
    }
    nodes: dict[str, list[tuple[int, str]]] = {
        "billing": [],
        "accounts": [],
        "claims": [],
    }
    current_module: str | None = None
    in_code = False

    for line in lines:
        if line in heading_to_module:
            current_module = heading_to_module[line]
            in_code = False
            continue
        if line.startswith("### 9.") and line not in heading_to_module:
            current_module = None
            in_code = False
            continue
        if current_module is None:
            continue
        if line == "```text":
            in_code = True
            continue
        if line == "```":
            in_code = False
            continue
        if not in_code:
            continue
        connector_positions = [
            position
            for connector in ("├── ", "└── ")
            if (position := line.find(connector)) >= 0
        ]
        if not connector_positions:
            continue
        position = min(connector_positions)
        label = line[position + 4 :].strip()
        depth = position // 4 + 1
        nodes[current_module].append((depth, label))

    leaves: dict[str, list[str]] = {}
    for module_key, module_nodes in nodes.items():
        module_leaves: list[str] = []
        for index, (depth, label) in enumerate(module_nodes):
            next_depth = (
                module_nodes[index + 1][0]
                if index + 1 < len(module_nodes)
                else 0
            )
            if next_depth <= depth:
                module_leaves.append(label)
        leaves[module_key] = module_leaves
    return leaves


def markdown_escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


