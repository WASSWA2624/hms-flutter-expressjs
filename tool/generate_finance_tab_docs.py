def editable_form_fields(tab: Tab, columns: list[str], profile: str) -> list[str]:
    if profile in {"overview", "analysis", "report", "audit"}:
        return []
    blocked_fragments = (
        "status",
        "created",
        "updated",
        "approved by",
        "approved at",
        "posted by",
        "posted at",
        "running",
        "available",
        "remaining",
        "variance",
        "last ",
        "journal entry",
        "paid amount",
        "allocated amount",
        "unallocated amount",
        "current balance",
        "opening balance",
        "closing balance",
        "total outstanding",
        "accumulated",
        "net book value",
        "row count",
        "exception count",
        "issued by",
        "received by",
        "processed by",
        "prepared by",
        "reviewed by",
        "requested by",
    )
    calculated_exact = {
        "subtotal",
        "total",
        "grand total",
        "tax",
        "difference",
        "current",
        "1–30 days",
        "31–60 days",
        "61–90 days",
        "over 90 days",
    }
    candidates: list[str] = []
    for index, column in enumerate(columns):
        lower = column.lower()
        if any(token in lower for token in blocked_fragments):
            continue
        if re.search(r"\b(count|age)\b", lower):
            continue
        if lower in calculated_exact or lower.startswith("total "):
            continue
        if profile in {"transaction", "reconciliation"} and any(
            token in lower
            for token in (
                "balance",
                "aging",
            )
        ):
            continue
        if tab.module_key == "claims" and profile == "transaction" and any(
            token in lower
            for token in (
                "submitted amount",
                "approved amount",
                "rejected amount",
                "paid amount",
                "outstanding amount",
                "patient share",
            )
        ):
            continue
        if (
            profile in {"transaction", "reconciliation"}
            and index == 0
            and re.search(r"\b(no\.?|number|reference)\b", lower)
        ):
            continue
        candidates.append(column)
    return candidates[:10]


