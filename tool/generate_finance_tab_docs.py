def validate_output_links(outputs: dict[Path, str]) -> None:
    expected = {path.resolve() for path in outputs}
    broken: list[str] = []
    link_pattern = re.compile(r"\[[^\]]*\]\(([^)]+)\)")
    for path, content in outputs.items():
        for raw_target in link_pattern.findall(content):
            target = raw_target.split("#", 1)[0].strip()
            if not target or re.match(r"^[a-z]+://", target) or target.startswith("mailto:"):
                continue
            resolved = (path.parent / target).resolve()
            if resolved not in expected and not resolved.exists():
                broken.append(
                    f"{path.relative_to(REPO_ROOT)} -> {raw_target}"
                )
    if broken:
        raise ValueError("Broken generated Markdown links:\n- " + "\n- ".join(broken))


def validate_output_content(outputs: dict[Path, str], tabs: list[Tab]) -> None:
    required_headings = (
        "## Purpose",
        "## Navigation and workspace placement",
        "## Primary table columns",
        "## Filters",
        "### Toolbar buttons",
        "### Row buttons",
        "### Bulk buttons",
        "## CRUD and workflow contract",
        "## Detail dialog and nested tables",
        "## Permissions and entitlement",
        "## Target API contract",
        "## Refactor work breakdown",
        "## Acceptance criteria",
    )
    problems: list[str] = []
    if len({tab.path for tab in tabs}) != len(tabs):
        problems.append("duplicate tab output path detected")
    for path, content in outputs.items():
        for line_number, line in enumerate(content.splitlines(), start=1):
            if line != line.rstrip():
                problems.append(
                    f"{path.relative_to(REPO_ROOT)}:{line_number} trailing whitespace"
                )
    for tab in tabs:
        content = outputs.get(tab.path, "")
        for heading in required_headings:
            if heading not in content:
                problems.append(
                    f"{tab.path.relative_to(REPO_ROOT)} missing {heading}"
                )
    if problems:
        raise ValueError(
            "Generated documentation content validation failed:\n- "
            + "\n- ".join(problems)
        )


def build_outputs() -> dict[Path, str]:
    tabs = all_tabs()
    expected_counts = {"billing": 24, "accounts": 100, "claims": 35}
    actual_counts = {
        key: sum(1 for tab in tabs if tab.module_key == key)
        for key in expected_counts
    }
    if actual_counts != expected_counts:
        raise ValueError(
            f"Tab inventory mismatch: expected {expected_counts}, got {actual_counts}"
        )

    source_tabs = parse_source_tabs()
    for module_key in expected_counts:
        configured = {
            tab.label for tab in tabs if tab.module_key == module_key
        }
        authoritative = set(source_tabs[module_key])
        if configured != authoritative:
            missing_from_generator = sorted(authoritative - configured)
            missing_from_source = sorted(configured - authoritative)
            raise ValueError(
                f"Section 9 menu mismatch for {module_key}: "
                f"missing from generator={missing_from_generator}; "
                f"missing from source={missing_from_source}"
            )

    columns = parse_source_columns()
    missing = [
        f"{tab.module_key}: {tab.label}"
        for tab in tabs
        if (tab.module_key, tab.label) not in columns
    ]
    if missing:
        raise ValueError("Tabs missing source columns:\n- " + "\n- ".join(missing))

    outputs: dict[Path, str] = {
        OUTPUT_ROOT / "README.md": root_readme(tabs),
        **shared_documents(),
    }
    for tab in tabs:
        outputs[tab.path] = render_tab(tab, columns[(tab.module_key, tab.label)])

    folder_titles: dict[Path, str] = {}
    for module_key, module in MODULES.items():
        folder_titles[OUTPUT_ROOT / module["folder"]] = module["menu"]
    for tab in tabs:
        current = OUTPUT_ROOT / tab.module["folder"]
        for group_label, group_slug in zip(tab.group_labels, tab.group_slugs):
            current = current / group_slug
            folder_titles[current] = group_label

    for folder, title in folder_titles.items():
        direct_tabs = [tab for tab in tabs if tab.directory == folder]
        child_folders = [
            (child_title, child)
            for child, child_title in folder_titles.items()
            if child.parent == folder
        ]
        outputs[folder / "README.md"] = render_folder_readme(
            folder, title, direct_tabs, child_folders
        )

    normalized = {
        path: content.rstrip() + "\n" for path, content in outputs.items()
    }
    validate_output_content(normalized, tabs)
    validate_output_links(normalized)
    return normalized


def generate(check: bool) -> int:
    outputs = build_outputs()
    expected_paths = set(outputs)
    existing_paths = (
        set(OUTPUT_ROOT.rglob("*.md")) if OUTPUT_ROOT.exists() else set()
    )

    if check:
        problems: list[str] = []
        for path, expected in outputs.items():
            if not path.exists():
                problems.append(f"missing: {path.relative_to(REPO_ROOT)}")
                continue
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                problems.append(f"outdated: {path.relative_to(REPO_ROOT)}")
        for path in sorted(existing_paths - expected_paths):
            problems.append(f"unexpected: {path.relative_to(REPO_ROOT)}")
        if problems:
            print("Finance tab documentation check failed:")
            for problem in problems:
                print(f"- {problem}")
            return 1
        print(
            f"Finance tab documentation is current: "
            f"{len(all_tabs())} tab files, {len(outputs)} total Markdown files."
        )
        return 0

    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    for stale in sorted(existing_paths - expected_paths):
        stale.unlink()

    print(
        f"Generated {len(all_tabs())} finance tab files and "
        f"{len(outputs) - len(all_tabs())} index/shared files under "
        f"{OUTPUT_ROOT.relative_to(REPO_ROOT)}."
    )
    return 0


