@dataclass(frozen=True)
class Tab:
    module_key: str
    group_labels: tuple[str, ...]
    group_slugs: tuple[str, ...]
    label: str
    source_section: str

    @property
    def module(self) -> dict[str, str]:
        return MODULES[self.module_key]

    @property
    def slug(self) -> str:
        return slugify(self.label)

    @property
    def directory(self) -> Path:
        return OUTPUT_ROOT / self.module["folder"] / Path(*self.group_slugs)

    @property
    def path(self) -> Path:
        return self.directory / f"{self.slug}.md"

    @property
    def menu_path(self) -> str:
        return " → ".join((self.module["menu"], *self.group_labels, self.label))


def slugify(value: str) -> str:
    value = value.replace("&", " and ").replace("–", "-").replace("—", "-")
    value = value.replace("/", " and ").replace("'", "")
    value = re.sub(r"[^A-Za-z0-9]+", "-", value)
    return value.strip("-").lower()


def snake_id(value: str) -> str:
    return slugify(value).replace("-", "_")


